export function common(lang: string) {
  return pickCopy(lang, commonCopy);
}

export function ratingCaption(lang: string, score: number): string {
  const c = common(lang);
  if (score >= 5) return c.ratingExcellent;
  if (score === 4) return c.ratingGood;
  if (score === 3) return c.ratingAverage;
  if (score === 2) return c.ratingPoor;
  return c.ratingVeryPoor;
}
