export type AppLang = 'zh' | 'en' | 'my';

export function tt(lang: string, zh: string, en: string, my: string): string {
  if (lang === 'en') return en;
  if (lang === 'my') return my;
  return zh;
}

export function pickCopy<T>(lang: string, dict: { zh: T; en: T; my: T }): T {
  if (lang === 'en') return dict.en;
  if (lang === 'my') return dict.my;
  return dict.zh;
}

