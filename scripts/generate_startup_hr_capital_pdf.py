    def section(self, title):
        self._n += 1
        self.add_page()
        self.set_text_color(26, 54, 93)
        self.set_font("wqy", size=16)
        self.cell(0, 10, f"{self._n}. {title}", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(212, 175, 55)
        self.set_line_width(0.7)
        self.line(10, self.get_y(), 200, self.get_y())
        self.set_line_width(0.2)
        self.ln(5)
        self.set_text_color(0, 0, 0)

    def sub(self, title):
        if self.get_y() > 255:
            self.add_page()
        self.ln(1)
        self.set_font("wqy", size=12)
        self.set_text_color(44, 82, 130)
        self.cell(0, 8, title, new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)

    def body(self, text):
        self.set_font("wqy", size=10)
        self.multi_cell(0, 5.8, text)
        self.ln(1.5)

    def note(self, text):
        self.set_fill_color(255, 248, 230)
        self.set_draw_color(212, 175, 55)
        self.set_font("wqy", size=9.5)
        self.multi_cell(0, 5.5, text, border=1, fill=True)
        self.ln(2.5)

    def bullets(self, items):
        self.set_font("wqy", size=10)
        w = self.w - self.l_margin - self.r_margin - 4
        for it in items:
            if self.get_y() > self.h - 22:
                self.add_page()
            self.set_x(14)
            self.multi_cell(w, 5.6, f"  -  {it}")
        self.ln(1.5)

    def table(self, headers, rows, col_widths=None):
        if col_widths is None:
            col_widths = [190 / len(headers)] * len(headers)
        if sum(col_widths) > 190:
            s = 190 / sum(col_widths)
            col_widths = [c * s for c in col_widths]
        self.set_font("wqy", size=8.5)
        self.set_fill_color(26, 54, 93)
        self.set_text_color(255, 255, 255)
        x0 = self.l_margin
        for i, h in enumerate(headers):
            self.set_x(x0 + sum(col_widths[:i]))
            self.cell(col_widths[i], 7.5, h, border=1, fill=True, align="C")
        self.ln()
        self.set_text_color(0, 0, 0)
        alt = False
        for row in rows:
            if self.get_y() > self.h - 28:
                self.add_page()
                self.set_fill_color(26, 54, 93)
                self.set_text_color(255, 255, 255)
                for i, h in enumerate(headers):
                    self.set_x(x0 + sum(col_widths[:i]))
                    self.cell(col_widths[i], 7.5, h, border=1, fill=True, align="C")
                self.ln()
                self.set_text_color(0, 0, 0)
            y0 = self.get_y()
            heights = []
            self.set_fill_color(245, 248, 252) if alt else self.set_fill_color(255, 255, 255)
            for i, cell in enumerate(row):
                self.set_xy(x0 + sum(col_widths[:i]), y0)
                self.multi_cell(col_widths[i], 5.2, str(cell), border=1, fill=True)
                heights.append(self.get_y() - y0)
            self.set_y(y0 + max(heights, default=7))
            alt = not alt
        self.ln(2.5)


